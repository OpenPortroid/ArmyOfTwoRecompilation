"""Generate aot/src/gpu/d3d_trace_list.inc: every XDK D3D entry point
(function in the D3D library range with callers outside it, or whose address
is taken) wrapped by D3D_TRACE_HOOK(addr)."""
import pickle

LO, HI = 0x82B0CD80, 0x82B34D80  # TU2 (v1: 0x82A40000, 0x82A68000)
db = pickle.load(open(r"C:\aot2\tools\fnindex.pkl", "rb"))
F, C = db["funcs"], db["callers"]
ind = lambda a: isinstance(a, int) and LO <= a < HI
taken = set()
for f in F.values():
    for c in f["consts"]:
        if ind(c) and c in F:
            taken.add(c)
# Entry points hooked elsewhere (they must call D3DTraceEnter themselves).
EXCLUDE = {0x82B2ACF0, 0x82B0FA20}  # perf_waits.cpp (D3D wait around Swap), aspect_ratio.cpp (CreateDevice)
out = []
for a in sorted(x for x in F if ind(x)):
    ext = [c for c in C.get(a, ()) if not ind(c)]
    if a in EXCLUDE:
        continue
    if ext or a in taken:
        out.append(a)
# XGraphics state cache writers of SET_STATE/IM_LOAD packets (outside D3D).
out += [0x82F0A178, 0x82F0A350, 0x82F0A530]
with open(r"C:\aot2\aot\src\gpu\d3d_trace_list.inc", "w") as f:
    f.write("// Generated by tools/gen_d3d_trace.py - D3D library entry points.\n")
    for a in out:
        f.write(f"D3D_TRACE_HOOK({a:08X})\n")
print(len(out), "entry points")
