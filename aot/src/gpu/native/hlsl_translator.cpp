  void HlslShaderTranslator::EmitVectorOp(const ParsedAluInstruction &instr, bool &predicate_written,
                                          uint32_t &nonfinite)
  {
    predicate_written = false;
    const auto &o = instr.vector_operands;
    auto op = [&](uint32_t i) { return Operand(o[i]); };
    auto same = [&](uint32_t a, uint32_t b) {
      return o[a].GetIdenticalComponents(o[b]) == 0b1111;
    };
    uint32_t nf[3] = {};
    for (uint32_t i = 0; i < instr.vector_operand_count && i < 3; ++i)
    {
      nf[i] = OperandNonfinite(o[i]);
    }
    // Componentwise ops pass infinity/NaN on; dot products and reductions to all.
    nonfinite = nf[0] | nf[1] | nf[2];
    auto mul = [&](uint32_t a, uint32_t b) {
      return same(a, b) || !(nf[a] | nf[b]) ? op(a) + " * " + op(b) : "xe_mul(" + op(a) + ", " + op(b) + ")";
    };
    std::string v;
    switch (instr.vector_opcode)
    {
    case AluVectorOpcode::kAdd:
      v = op(0) + " + " + op(1);
      break;
    case AluVectorOpcode::kMul:
      v = mul(0, 1);
      break;
    case AluVectorOpcode::kMad:
      v = mul(0, 1) + " + " + op(2);
      break;
    case AluVectorOpcode::kMax:
      v = same(0, 1) ? op(0) : "xe_max(" + op(0) + ", " + op(1) + ")";
      break;
    case AluVectorOpcode::kMin:
      v = same(0, 1) ? op(0) : "xe_min(" + op(0) + ", " + op(1) + ")";
      break;
    case AluVectorOpcode::kSeq:
      nonfinite = 0;
      v = "float4(" + op(0) + " == " + op(1) + ")";
      break;
    case AluVectorOpcode::kSgt:
      nonfinite = 0;
      v = "float4(" + op(0) + " > " + op(1) + ")";
      break;
    case AluVectorOpcode::kSge:
      nonfinite = 0;
      v = "float4(" + op(0) + " >= " + op(1) + ")";
      break;
    case AluVectorOpcode::kSne:
      nonfinite = 0;
      v = "float4(" + op(0) + " != " + op(1) + ")";
      break;
    case AluVectorOpcode::kFrc:
      v = "frac(" + op(0) + ")";
      break;
    case AluVectorOpcode::kTrunc:
      v = "trunc(" + op(0) + ")";
      break;
    case AluVectorOpcode::kFloor:
      v = "floor(" + op(0) + ")";
      break;
    // The result is operand 1 or 2: the condition's infinity doesn't reach it.
    case AluVectorOpcode::kCndEq:
      v = "((" + op(0) + " == 0.0) ? " + op(1) + " : " + op(2) + ")";
      nonfinite = nf[1] | nf[2];
      break;
    case AluVectorOpcode::kCndGe:
      v = "((" + op(0) + " >= 0.0) ? " + op(1) + " : " + op(2) + ")";
      nonfinite = nf[1] | nf[2];
      break;
    case AluVectorOpcode::kCndGt:
      v = "((" + op(0) + " > 0.0) ? " + op(1) + " : " + op(2) + ")";
      nonfinite = nf[1] | nf[2];
      break;
    case AluVectorOpcode::kDp4:
    case AluVectorOpcode::kDp3:
    case AluVectorOpcode::kDp2Add:
    {
      uint32_t n = instr.vector_opcode == AluVectorOpcode::kDp4   ? 4
                   : instr.vector_opcode == AluVectorOpcode::kDp3 ? 3
                                                                  : 2;
      std::string a = op(0), b = op(1);
      std::string sum;
      for (uint32_t i = 0; i < n; ++i)
      {
        std::string term = (o[0].GetIdenticalComponents(o[1]) & (1u << i)) || !(((nf[0] | nf[1]) >> i) & 1)
                               ? fmt::format("{0}.{1} * {2}.{1}", a, kComp[i], b)
                               : fmt::format("xe_mul1({0}.{1}, {2}.{1})", a, kComp[i], b);
        sum += (i ? " + " : "") + term;
      }
      if (n == 2)
      {
        sum += " + " + op(2) + ".x";
      }
      v = "(" + sum + ").xxxx";
      nonfinite = ((nf[0] | nf[1]) & ((1u << n) - 1)) || (n == 2 && (nf[2] & 1)) ? 0xF : 0;
      break;
    }
    case AluVectorOpcode::kCube:
    {
      // operands[0] is .zzxy; result: T, S, 2 * major axis, face ID.
      std::string s = op(0);
      Line(fmt::format("float3 xe_cube_dir = float3({0}.z, {0}.w, {0}.x);", s));
      Line("float4 xe_cube;");
      Open("if (abs(xe_cube_dir.z) >= abs(xe_cube_dir.x) && abs(xe_cube_dir.z) >= abs(xe_cube_dir.y))");
      Line("xe_cube = float4(-xe_cube_dir.y, xe_cube_dir.z < 0.0 ? -xe_cube_dir.x : xe_cube_dir.x, "
           "2.0 * xe_cube_dir.z, xe_cube_dir.z < 0.0 ? 5.0 : 4.0);");
      Close();
      Open("else if (abs(xe_cube_dir.y) >= abs(xe_cube_dir.x))");
      Line("xe_cube = float4(xe_cube_dir.y < 0.0 ? -xe_cube_dir.z : xe_cube_dir.z, xe_cube_dir.x, "
           "2.0 * xe_cube_dir.y, xe_cube_dir.y < 0.0 ? 3.0 : 2.0);");
      Close();
      Open("else");
      Line("xe_cube = float4(-xe_cube_dir.y, xe_cube_dir.x < 0.0 ? xe_cube_dir.z : -xe_cube_dir.z, "
           "2.0 * xe_cube_dir.x, xe_cube_dir.x < 0.0 ? 1.0 : 0.0);");
      Close();
      v = "xe_cube";
      nonfinite = nf[0] ? 0xF : 0;
      break;
    }
    case AluVectorOpcode::kMax4:
    {
      std::string a = op(0);
      v = fmt::format("max(max({0}.x, {0}.y), max({0}.z, {0}.w)).xxxx", a);
      nonfinite = nf[0] ? 0xF : 0;
      break;
    }
    case AluVectorOpcode::kSetpEqPush:
    case AluVectorOpcode::kSetpNePush:
    case AluVectorOpcode::kSetpGtPush:
    case AluVectorOpcode::kSetpGePush:
    {
      predicate_written = true;
      const char *cmp = instr.vector_opcode == AluVectorOpcode::kSetpEqPush   ? "=="
                        : instr.vector_opcode == AluVectorOpcode::kSetpNePush ? "!="
                        : instr.vector_opcode == AluVectorOpcode::kSetpGtPush ? ">"
                                                                              : ">=";
      std::string a = op(0), b = op(1);
      Line(fmt::format("float4 xe_push_a = {}; float4 xe_push_b = {};", a, b));
      Line(fmt::format("xe_p0 = (xe_push_a.w == 0.0) && (xe_push_b.w {} 0.0);", cmp));
      v = fmt::format("(((xe_push_a.x == 0.0) && (xe_push_b.x {} 0.0)) ? 0.0 : xe_push_a.x + 1.0).xxxx",
                      cmp);
      nonfinite = (nf[0] & 1) ? 0xF : 0;
      break;
    }
    case AluVectorOpcode::kKillEq:
    case AluVectorOpcode::kKillGt:
    case AluVectorOpcode::kKillGe:
    case AluVectorOpcode::kKillNe:
    {
      const char *cmp = instr.vector_opcode == AluVectorOpcode::kKillEq   ? "=="
                        : instr.vector_opcode == AluVectorOpcode::kKillGt ? ">"
                        : instr.vector_opcode == AluVectorOpcode::kKillGe ? ">="
                                                                          : "!=";
      Line(fmt::format("bool xe_kill = any({} {} {});", op(0), cmp, op(1)));
      if (is_pixel_shader())
      {
        Open("if (xe_kill)");
        Line("discard;");
        Close();
      }
      v = "float(xe_kill).xxxx";
      nonfinite = 0;
      break;
    }
    case AluVectorOpcode::kDst:
    {
      std::string a = op(0), b = op(1);
      v = ((nf[0] | nf[1]) & 2) ? fmt::format("float4(1.0, xe_mul1({0}.y, {1}.y), {0}.z, {1}.w)", a, b)
                                : fmt::format("float4(1.0, {0}.y * {1}.y, {0}.z, {1}.w)", a, b);
      break;
    }
    case AluVectorOpcode::kMaxA:
    {
      std::string a = op(0);
      Line(fmt::format("xe_a0 = int(clamp(floor({}.w + 0.5), -256.0, 255.0));", a));
      v = same(0, 1) ? a : "xe_max(" + a + ", " + op(1) + ")";
      break;
    }
    default:
      EmitTranslationError("unknown vector ALU opcode");
      v = "float4(0.0, 0.0, 0.0, 0.0)";
      break;
    }
    if (!track_finite_)
    {
      nonfinite = 0xF;
    }
    Line("float4 xe_vec = " + v + ";");
  }

  void HlslShaderTranslator::EmitScalarOp(const ParsedAluInstruction &instr, bool &predicate_written)
  {
    predicate_written = false;
    if (instr.scalar_opcode == AluScalarOpcode::kRetainPrev)
    {
      return;
    }
    const auto &o = instr.scalar_operands;
    // Whether a (operand 0's first component), b (its second), c1 (operand
    // 1's first) and the previous result may be infinity or NaN.
    uint32_t nf0 = instr.scalar_operand_count >= 1 ? OperandNonfinite(o[0]) : 0;
    uint32_t nf1 = instr.scalar_operand_count >= 2 ? OperandNonfinite(o[1]) : 0;
    bool nfa = nf0 & 1, nfb = nf0 & 2, nfc = nf1 & 1, nfp = ps_nonfinite_ || !track_finite_;
    auto mul1 = [&](const std::string &x, bool nfx, const std::string &y, bool nfy) {
      return nfx || nfy ? "xe_mul1(" + x + ", " + y + ")" : x + " * " + y;
    };
    // What this result may hold: by default whatever its operands may.
    bool nfr = nfa || nfb;
    std::string a, b, c1;
    if (instr.scalar_operand_count >= 1)
    {
      std::string s = Operand(o[0]);
      a = s + ".x";
      b = s + ".y";
    }
    if (instr.scalar_operand_count >= 2)
    {
      c1 = Operand(o[1]) + ".x";
    }
    bool ab_same = o[0].components[0] == o[0].components[1];
    std::string r;
    switch (instr.scalar_opcode)
    {
    case AluScalarOpcode::kAdds: r = a + " + " + b; break;
    case AluScalarOpcode::kAddsPrev: r = a + " + xe_ps"; nfr = nfa || nfp; break;
    case AluScalarOpcode::kMuls: r = ab_same ? a + " * " + b : mul1(a, nfa, b, nfb); break;
    case AluScalarOpcode::kMulsPrev: r = mul1(a, nfa, "xe_ps", nfp); nfr = nfa || nfp; break;
    case AluScalarOpcode::kMulsPrev2:
      r = fmt::format("((xe_ps != {0}) && (abs(xe_ps) <= {1}) && (abs({3}) <= {1}) && ({3} > 0.0)) "
                      "? xe_mul1({2}, xe_ps) : {0}",
                      F(-FLT_MAX), F(FLT_MAX), a, b);
      nfr = nfa || nfp;
      break;
    case AluScalarOpcode::kMaxs: r = ab_same ? a : "xe_max1(" + a + ", " + b + ")"; break;
    case AluScalarOpcode::kMins: r = ab_same ? a : "xe_min1(" + a + ", " + b + ")"; break;
    case AluScalarOpcode::kSeqs: r = "float(" + a + " == 0.0)"; nfr = false; break;
    case AluScalarOpcode::kSgts: r = "float(" + a + " > 0.0)"; nfr = false; break;
    case AluScalarOpcode::kSges: r = "float(" + a + " >= 0.0)"; nfr = false; break;
    case AluScalarOpcode::kSnes: r = "float(" + a + " != 0.0)"; nfr = false; break;
    case AluScalarOpcode::kFrcs: r = "frac(" + a + ")"; nfr = nfa; break;
    case AluScalarOpcode::kTruncs: r = "trunc(" + a + ")"; nfr = nfa; break;
    case AluScalarOpcode::kFloors: r = "floor(" + a + ")"; nfr = nfa; break;
    case AluScalarOpcode::kExp: r = "exp2(" + a + ")"; nfr = true; break;
    case AluScalarOpcode::kLogc:
      r = fmt::format("max(log2({}), {})", a, F(-FLT_MAX));
      nfr = nfa;
      break;
    case AluScalarOpcode::kLog: r = "log2(" + a + ")"; nfr = true; break;
    case AluScalarOpcode::kRcpc:
      r = fmt::format("clamp(1.0 / {}, {}, {})", a, F(-FLT_MAX), F(FLT_MAX));
      nfr = nfa;
      break;
    case AluScalarOpcode::kRsqc:
      r = fmt::format("clamp(rsqrt({}), {}, {})", a, F(-FLT_MAX), F(FLT_MAX));
      nfr = true;
      break;
    case AluScalarOpcode::kRcpf:
      Line(fmt::format("float xe_rcp = 1.0 / {};", a));
      r = "(isinf(xe_rcp) ? asfloat(asuint(xe_rcp) & 0x80000000u) : xe_rcp)";
      nfr = nfa;
      break;
    case AluScalarOpcode::kRsqf:
      Line(fmt::format("float xe_rcp = rsqrt({});", a));
      r = "(isinf(xe_rcp) ? asfloat(asuint(xe_rcp) & 0x80000000u) : xe_rcp)";
      nfr = true;
      break;
    case AluScalarOpcode::kRcp: r = "1.0 / " + a; nfr = true; break;
    case AluScalarOpcode::kRsq: r = "rsqrt(" + a + ")"; nfr = true; break;
    case AluScalarOpcode::kMaxAs:
      Line(fmt::format("xe_a0 = int(clamp(floor({} + 0.5), -256.0, 255.0));", a));
      r = ab_same ? a : "xe_max1(" + a + ", " + b + ")";
      break;
    case AluScalarOpcode::kMaxAsf:
      Line(fmt::format("xe_a0 = int(clamp(floor({}), -256.0, 255.0));", a));
      r = ab_same ? a : "xe_max1(" + a + ", " + b + ")";
      break;
    case AluScalarOpcode::kSubs: r = a + " - " + b; break;
    case AluScalarOpcode::kSubsPrev: r = a + " - xe_ps"; nfr = nfa || nfp; break;
    case AluScalarOpcode::kSetpEq:
    case AluScalarOpcode::kSetpNe:
    case AluScalarOpcode::kSetpGt:
    case AluScalarOpcode::kSetpGe:
    {
      predicate_written = true;
      const char *cmp = instr.scalar_opcode == AluScalarOpcode::kSetpEq   ? "=="
                        : instr.scalar_opcode == AluScalarOpcode::kSetpNe ? "!="
                        : instr.scalar_opcode == AluScalarOpcode::kSetpGt ? ">"
                                                                          : ">=";
      Line(fmt::format("xe_p0 = {} {} 0.0;", a, cmp));
      r = "(xe_p0 ? 0.0 : 1.0)";
      nfr = false;
      break;
    }
    case AluScalarOpcode::kSetpInv:
      predicate_written = true;
      Line(fmt::format("float xe_inv_a = {};", a));
      Line("xe_p0 = xe_inv_a == 1.0;");
      r = "(xe_p0 ? 0.0 : (xe_inv_a == 0.0 ? 1.0 : xe_inv_a))";
      nfr = nfa;
      break;
    case AluScalarOpcode::kSetpPop:
      predicate_written = true;
      Line(fmt::format("float xe_pop = {} - 1.0;", a));
      Line("xe_p0 = xe_pop <= 0.0;");
      r = "(xe_p0 ? 0.0 : xe_pop)";
      nfr = nfa;
      break;
    case AluScalarOpcode::kSetpClr:
      predicate_written = true;
      Line("xe_p0 = false;");
      r = F(FLT_MAX);
      nfr = false;
      break;
    case AluScalarOpcode::kSetpRstr:
      predicate_written = true;
      Line(fmt::format("xe_p0 = {} == 0.0;", a));
      r = "(xe_p0 ? 0.0 : " + a + ")";
      nfr = nfa;
      break;
    case AluScalarOpcode::kKillsEq:
    case AluScalarOpcode::kKillsGt:
    case AluScalarOpcode::kKillsGe:
    case AluScalarOpcode::kKillsNe:
    case AluScalarOpcode::kKillsOne:
    {
      std::string cond = instr.scalar_opcode == AluScalarOpcode::kKillsEq   ? a + " == 0.0"
                         : instr.scalar_opcode == AluScalarOpcode::kKillsGt ? a + " > 0.0"
                         : instr.scalar_opcode == AluScalarOpcode::kKillsGe ? a + " >= 0.0"
                         : instr.scalar_opcode == AluScalarOpcode::kKillsNe ? a + " != 0.0"
                                                                            : a + " == 1.0";
      Line("bool xe_skill = " + cond + ";");
      if (is_pixel_shader())
      {
        Open("if (xe_skill)");
        Line("discard;");
        Close();
      }
      r = "float(xe_skill)";
      nfr = false;
      break;
    }
    case AluScalarOpcode::kSqrt: r = "sqrt(" + a + ")"; nfr = true; break;
    case AluScalarOpcode::kMulsc0:
    case AluScalarOpcode::kMulsc1: r = mul1(a, nfa, c1, nfc); nfr = nfa || nfc; break;
    case AluScalarOpcode::kAddsc0:
    case AluScalarOpcode::kAddsc1: r = a + " + " + c1; nfr = nfa || nfc; break;
    case AluScalarOpcode::kSubsc0:
    case AluScalarOpcode::kSubsc1: r = a + " - " + c1; nfr = nfa || nfc; break;
    case AluScalarOpcode::kSin: r = "sin(" + a + ")"; nfr = nfa; break;
    case AluScalarOpcode::kCos: r = "cos(" + a + ")"; nfr = nfa; break;
    default:
      EmitTranslationError("unknown scalar ALU opcode");
      r = "0.0";
      break;
    }
    Line("xe_ps = " + r + ";");
    // Sticky like the registers: xe_ps is kept across predicated instructions.
    ps_nonfinite_ = (ps_nonfinite_ && !unconditional_) || nfr || !track_finite_;
  }

  void HlslShaderTranslator::ProcessAluInstruction(const ParsedAluInstruction &instr, uint8_t)
  {
    if (instr.IsNop())
    {
      return;
    }
    TrackPositionWrite(instr);
    SetInstructionPredication(instr.is_predicated, instr.predicate_condition);
    Open("");
    bool pw_vector = false, pw_scalar = false;
    unconditional_ = !instr.is_predicated && !conditional_exec_ && current_label_ == 0;
    uint32_t vector_nonfinite = 0xF;
    EmitVectorOp(instr, pw_vector, vector_nonfinite);
    EmitScalarOp(instr, pw_scalar);
    StoreResult(instr.vector_and_constant_result, "xe_vec", vector_nonfinite);
    StoreResult(instr.scalar_result, "xe_ps.xxxx", ps_nonfinite_ ? 0xF : 0);
    unconditional_ = false;
    Close();
    if (pw_vector || pw_scalar)
    {
      // Following instructions must re-check the predicate.
      ClosePredication();
    }
  }

  // A position export counts as pass-through when it is an unconditional
  // `max oPos.xy, rN.xy, rN.xy` of the register the first vertex fetch wrote
  // its x/y to, with nothing written to that register in between.
  void HlslShaderTranslator::TrackPositionWrite(const ParsedAluInstruction &instr)
  {
    const InstructionResult &vr = instr.vector_and_constant_result;
    if (vr.storage_target == InstructionStorageTarget::kPosition && (vr.GetUsedWriteMask() & 0b11))
    {
      const InstructionOperand &a = instr.vector_operands[0];
      bool pass = position_register_ >= 0 && !instr.is_predicated && !conditional_exec_ && !use_loop_ &&
                  !vr.is_clamped && instr.vector_opcode == AluVectorOpcode::kMax &&
                  a.GetIdenticalComponents(instr.vector_operands[1]) == 0b1111 &&
                  a.storage_source == InstructionStorageSource::kRegister &&
                  a.storage_addressing_mode == InstructionStorageAddressingMode::kAbsolute &&
                  a.storage_index == uint32_t(position_register_) && !a.is_negated && !a.is_absolute_value &&
                  a.GetComponent(0) == SwizzleSource::kX && a.GetComponent(1) == SwizzleSource::kY &&
                  vr.components[0] == SwizzleSource::kX && vr.components[1] == SwizzleSource::kY;
      position_state_ = (pass && position_state_ >= 0) ? 1 : -1;
    }
    const InstructionResult &sr = instr.scalar_result;
    if (sr.storage_target == InstructionStorageTarget::kPosition && (sr.GetUsedWriteMask() & 0b11))
    {
      position_state_ = -1;
    }
    TrackRegisterWrite(vr);
    TrackRegisterWrite(sr);
  }

  void HlslShaderTranslator::TrackRegisterWrite(const InstructionResult &result)
  {
    if (position_register_ >= 0 && result.storage_target == InstructionStorageTarget::kRegister &&
        (result.GetUsedWriteMask() & 0b11) &&
        (result.storage_addressing_mode != InstructionStorageAddressingMode::kAbsolute ||
         result.storage_index == uint32_t(position_register_)))
    {
      position_register_ = -2;
    }
  }

