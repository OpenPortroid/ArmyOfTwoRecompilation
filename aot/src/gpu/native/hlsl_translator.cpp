  HlslModification HlslShaderTranslator::modification() const
  {
    HlslModification m;
    m.value = current_translation().modification();
    return m;
  }

  uint32_t HlslShaderTranslator::GetModificationRegisterCount() const
  {
    uint32_t n = modification().register_count;
    return n ? n : xenos::kMaxShaderTempRegisters;
  }

  void HlslShaderTranslator::Reset()
  {
    ShaderTranslator::Reset();
    body_.clear();
    indent_ = 0;
    exec_open_ = false;
    predicate_open_ = false;
    temp_counter_ = 0;
    position_fetch_ = {};
    position_register_ = -1;
    position_state_ = 0;
    conditional_exec_ = false;
    std::fill(std::begin(nonfinite_), std::end(nonfinite_), uint8_t(0));
    ps_nonfinite_ = false;
    track_finite_ = false;
  }

  void HlslShaderTranslator::Line(const std::string &s)
  {
    body_.append(size_t(indent_) * 2 + 2, ' ');
    body_ += s;
    body_ += '\n';
  }

  void HlslShaderTranslator::Open(const std::string &s)
  {
    Line(s + " {");
    ++indent_;
  }

  void HlslShaderTranslator::Close()
  {
    --indent_;
    Line("}");
  }

  std::string HlslShaderTranslator::BoolConstantTest(uint32_t index) const
  {
    return fmt::format("((xe_bool_loop[{}][{}] & {}u) != 0u)", index >> 7, (index >> 5) & 3,
                       1u << (index & 31));
  }

  std::string HlslShaderTranslator::LoopConstant(uint32_t index) const
  {
    return fmt::format("xe_bool_loop[{}][{}]", 2 + (index >> 2), index & 3);
  }

  void HlslShaderTranslator::PreProcessControlFlowInstructions(
      std::vector<ucode::ControlFlowInstruction> instrs)
  {
    use_loop_ = false;
    for (size_t i = 0; i < instrs.size(); ++i)
    {
      switch (instrs[i].opcode())
      {
      case ucode::ControlFlowOpcode::kLoopStart:
      case ucode::ControlFlowOpcode::kLoopEnd:
      case ucode::ControlFlowOpcode::kCondCall:
      case ucode::ControlFlowOpcode::kReturn:
        use_loop_ = true;
        break;
      case ucode::ControlFlowOpcode::kCondJmp:
        if (instrs[i].cond_jmp.address() <= i)
        {
          use_loop_ = true;
        }
        break;
      default:
        break;
      }
    }
    // The translator calls this after StartTranslation (and before any
    // instruction): the main loop depends on this shader's control flow, not
    // on the previous shader's.
    current_label_ = 0;
    track_finite_ = !use_loop_ && REXCVAR_GET(ao2_native_gpu_finite_mul);
    if (use_loop_)
    {
      // Bounded so a mistranslated loop can't hang the GPU (TDR).
      Line("uint xe_iterations = 0u;");
      Open("[loop] while (++xe_iterations < 65536u)");
    }
    Open("if (xe_pc <= 0u)");
  }

  void HlslShaderTranslator::ReopenLabelGuard()
  {
    // Skip the rest of the current label block if pc moved past it.
    CloseExecConditional();
    Close();
    Open(fmt::format("if (xe_pc <= {}u)", current_label_));
  }

  void HlslShaderTranslator::StartTranslation()
  {
    // Main loop with `if (pc <= label)` blocks, see ProcessLabel.
    Line("uint xe_pc = 0u;");
    Line("bool xe_p0 = false;");
    Line("int xe_a0 = 0;");
    Line("int4 xe_aL = 0;");
    Line("uint4 xe_loop_count = 0u;");
    Line("float xe_ps = 0.0;");
    Line("float4 xe_grad_h = 0.0, xe_grad_v = 0.0;");
    Line("float xe_lod = 0.0;");
    Line("uint xe_vfetch_address = 0u;");
    // The main loop and the first label block: PreProcessControlFlowInstructions.
  }

  void HlslShaderTranslator::ProcessLabel(uint32_t cf_index)
  {
    if (cf_index == 0)
    {
      return;
    }
    CloseExecConditional();
    Close();
    Open(fmt::format("if (xe_pc <= {}u)", cf_index));
    current_label_ = cf_index;
  }

  void HlslShaderTranslator::OpenExecConditional(ParsedExecInstruction::Type type,
                                                 uint32_t bool_index, bool condition)
  {
    CloseExecConditional();
    if (type == ParsedExecInstruction::Type::kConditional)
    {
      Open(fmt::format("if ({} == {})", BoolConstantTest(bool_index), condition ? "true" : "false"));
      exec_open_ = true;
    }
    else if (type == ParsedExecInstruction::Type::kPredicated)
    {
      Open(fmt::format("if (xe_p0 == {})", condition ? "true" : "false"));
      exec_open_ = true;
    }
  }

  void HlslShaderTranslator::CloseExecConditional()
  {
    ClosePredication();
    if (exec_open_)
    {
      Close();
      exec_open_ = false;
    }
  }

  void HlslShaderTranslator::SetInstructionPredication(bool predicated, bool condition)
  {
    if (!predicated)
    {
      ClosePredication();
      return;
    }
    if (predicate_open_ && predicate_condition_ == condition)
    {
      return;
    }
    ClosePredication();
    Open(fmt::format("if (xe_p0 == {})", condition ? "true" : "false"));
    predicate_open_ = true;
    predicate_condition_ = condition;
  }

  void HlslShaderTranslator::ClosePredication()
  {
    if (predicate_open_)
    {
      Close();
      predicate_open_ = false;
    }
  }

  void HlslShaderTranslator::ProcessExecInstructionBegin(const ParsedExecInstruction &instr)
  {
    conditional_exec_ = instr.type != ParsedExecInstruction::Type::kUnconditional;
    OpenExecConditional(instr.type, instr.bool_constant_index, instr.condition);
  }

  void HlslShaderTranslator::ProcessExecInstructionEnd(const ParsedExecInstruction &instr)
  {
    if (instr.is_end)
    {
      // Past every label: the rest is skipped and the main loop (if any)
      // ends at its final break. (A `break` here, right before that final
      // one, crashed FXC - "internal error: compilation aborted".)
      ClosePredication();
      Line("xe_pc = 0xFFFFFFFFu;");
      ReopenLabelGuard();
      return;
    }
    CloseExecConditional();
  }

  void HlslShaderTranslator::ProcessLoopStartInstruction(const ParsedLoopStartInstruction &instr)
  {
    CloseExecConditional();
    std::string c = LoopConstant(instr.loop_constant_index);
    Open("");
    Line(fmt::format("uint xe_count = {} & 0xFFu;", c));
    Open("if (xe_count == 0u)");
    Line(fmt::format("xe_pc = {}u;", instr.loop_skip_address));
    Line("continue;");
    Close();
    Line("xe_loop_count = uint4(xe_count, xe_loop_count.xyz);");
    if (instr.is_repeat)
    {
      Line("xe_aL = int4(xe_aL.x, xe_aL.xyz);");
    }
    else
    {
      Line(fmt::format("xe_aL = int4(int(({} >> 8) & 0xFFu), xe_aL.xyz);", c));
    }
    Close();
  }

  void HlslShaderTranslator::ProcessLoopEndInstruction(const ParsedLoopEndInstruction &instr)
  {
    CloseExecConditional();
    Line("xe_loop_count.x -= 1u;");
    std::string cond = "xe_loop_count.x == 0u";
    if (instr.is_predicated_break)
    {
      cond = fmt::format("{} || xe_p0 == {}", cond, instr.predicate_condition ? "true" : "false");
    }
    Open(fmt::format("if ({})", cond));
    Line("xe_loop_count = uint4(xe_loop_count.yzw, 0u);");
    Line("xe_aL = int4(xe_aL.yzw, 0);");
    Close();
    Open("else");
    Line(fmt::format("xe_aL.x += int(({0} << 8) & 0xFF000000u) >> 24;",
                     LoopConstant(instr.loop_constant_index)));
    Line(fmt::format("xe_pc = {}u;", instr.loop_body_address));
    Line("continue;");
    Close();
  }

  void HlslShaderTranslator::ProcessCallInstruction(const ParsedCallInstruction &)
  {
    EmitTranslationError("call is not supported by the HLSL translator", false);
  }

  void HlslShaderTranslator::ProcessReturnInstruction(const ParsedReturnInstruction &)
  {
    EmitTranslationError("return is not supported by the HLSL translator", false);
  }

  void HlslShaderTranslator::ProcessJumpInstruction(const ParsedJumpInstruction &instr)
  {
    ParsedExecInstruction::Type type = ParsedExecInstruction::Type::kUnconditional;
    if (instr.type == ParsedJumpInstruction::Type::kConditional)
    {
      type = ParsedExecInstruction::Type::kConditional;
    }
    else if (instr.type == ParsedJumpInstruction::Type::kPredicated)
    {
      type = ParsedExecInstruction::Type::kPredicated;
    }
    OpenExecConditional(type, instr.bool_constant_index, instr.condition);
    Line(fmt::format("xe_pc = {}u;", instr.target_address));
    if (use_loop_)
    {
      Line("continue;");
      CloseExecConditional();
    }
    else
    {
      ReopenLabelGuard();
    }
  }

  std::string HlslShaderTranslator::RegisterName(uint32_t index,
                                                 InstructionStorageAddressingMode mode) const
  {
    if (mode == InstructionStorageAddressingMode::kLoopRelative)
    {
      return fmt::format("xe_r[clamp({} + xe_aL.x, 0, {})]", index, register_count() - 1);
    }
    return fmt::format("xe_r[{}]", index);
  }

  std::string HlslShaderTranslator::Operand(const InstructionOperand &op) const
  {
    std::string base;
    switch (op.storage_source)
    {
    case InstructionStorageSource::kRegister:
      base = RegisterName(op.storage_index, op.storage_addressing_mode);
      break;
    case InstructionStorageSource::kConstantFloat:
      switch (op.storage_addressing_mode)
      {
      case InstructionStorageAddressingMode::kAddressRegisterRelative:
        base = fmt::format("xe_c[uint({} + xe_a0) & 255u]", op.storage_index);
        break;
      case InstructionStorageAddressingMode::kLoopRelative:
        base = fmt::format("xe_c[uint({} + xe_aL.x) & 255u]", op.storage_index);
        break;
      default:
        base = fmt::format("xe_c[{}]", op.storage_index);
        break;
      }
      break;
    default:
      // Fetch constants are not ALU operands.
      base = "float4(0.0, 0.0, 0.0, 0.0)";
      break;
    }
    std::string swizzle = ".";
    for (uint32_t i = 0; i < 4; ++i)
    {
      swizzle += kComp[uint32_t(op.GetComponent(i)) & 3];
    }
    std::string v = base + swizzle;
    if (op.is_absolute_value)
    {
      v = "abs(" + v + ")";
    }
    if (op.is_negated)
    {
      v = "-" + v;
    }
    return "(" + v + ")";
  }

  uint32_t HlslShaderTranslator::OperandNonfinite(const InstructionOperand &op) const
  {
    if (!track_finite_)
    {
      return 0xF;
    }
    if (op.storage_source == InstructionStorageSource::kConstantFloat)
    {
      return 0;
    }
    if (op.storage_source != InstructionStorageSource::kRegister ||
        op.storage_addressing_mode != InstructionStorageAddressingMode::kAbsolute || op.storage_index >= 256)
    {
      return 0xF;
    }
    uint32_t mask = 0;
    for (uint32_t i = 0; i < 4; ++i)
    {
      SwizzleSource s = op.GetComponent(i);
      if (s != SwizzleSource::k0 && s != SwizzleSource::k1 && ((nonfinite_[op.storage_index] >> (uint32_t(s) & 3)) & 1))
      {
        mask |= 1u << i;
      }
    }
    return mask;
  }

  std::string HlslShaderTranslator::OperandComponent(const InstructionOperand &op,
                                                     uint32_t component) const
  {
    return Operand(op) + "." + kComp[component];
  }

  void HlslShaderTranslator::StoreResult(const InstructionResult &result, const std::string &value,
                                         uint32_t nonfinite)
  {
    uint32_t mask = result.GetUsedWriteMask();
    if (!mask)
    {
      return;
    }
    if (result.storage_target == InstructionStorageTarget::kRegister && unconditional_ &&
        result.storage_addressing_mode == InstructionStorageAddressingMode::kAbsolute && result.storage_index < 256)
    {
      nonfinite_[result.storage_index] &= uint8_t(~mask);
    }
    if (result.storage_target == InstructionStorageTarget::kRegister && !result.is_clamped)
    {
      for (uint32_t i = 0; i < 4; ++i)
      {
        SwizzleSource s = result.components[i];
        if (!(mask & (1u << i)) || s == SwizzleSource::k0 || s == SwizzleSource::k1 ||
            !((nonfinite >> (uint32_t(s) & 3)) & 1))
        {
          continue;
        }
        if (result.storage_addressing_mode == InstructionStorageAddressingMode::kAbsolute &&
            result.storage_index < 256)
        {
          nonfinite_[result.storage_index] |= uint8_t(1u << i);
          continue;
        }
        else
        {
          for (uint8_t &r : nonfinite_)
          {
            r |= uint8_t(1u << i);
          }
        }
      }
    }
    std::string target;
    switch (result.storage_target)
    {
    case InstructionStorageTarget::kRegister:
      target = RegisterName(result.storage_index, result.storage_addressing_mode);
      break;
    case InstructionStorageTarget::kInterpolator:
      if (result.storage_index >= 16)
      {
        return;
      }
      target = fmt::format("xe_out.o[{}]", result.storage_index);
      break;
    case InstructionStorageTarget::kPosition:
      target = "xe_position";
      break;
    case InstructionStorageTarget::kPointSizeEdgeFlagKillVertex:
      target = "xe_out.misc";
      break;
    case InstructionStorageTarget::kColor:
      target = fmt::format("xe_color[{}]", result.storage_index & 3);
      break;
    case InstructionStorageTarget::kDepth:
      target = "xe_depth";
      break;
    default:
      // Memory export is not supported.
      return;
    }
    std::string src = fmt::format("xe_store{}", temp_counter_++);
    Open("");
    Line(fmt::format("float4 {} = {};", src, value));
    if (result.is_clamped)
    {
      Line(fmt::format("{0} = saturate({0});", src));
    }
    for (uint32_t i = 0; i < 4; ++i)
    {
      if (!(mask & (1u << i)))
      {
        continue;
      }
      std::string lhs = target;
      if (result.storage_target == InstructionStorageTarget::kDepth)
      {
        if (i != 0)
        {
          continue;
        }
      }
      else
      {
        lhs += std::string(".") + kComp[i];
      }
      std::string rhs;
      switch (result.components[i])
      {
      case SwizzleSource::k0:
        rhs = "0.0";
        break;
      case SwizzleSource::k1:
        rhs = "1.0";
        break;
      default:
        rhs = src + "." + kComp[uint32_t(result.components[i]) & 3];
        break;
      }
      Line(fmt::format("{} = {};", lhs, rhs));
    }
    Close();
  }

