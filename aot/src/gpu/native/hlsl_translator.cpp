    const char kComp[] = {'x', 'y', 'z', 'w'};

    std::string F(float v)
    {
      if (std::isinf(v))
      {
        return v > 0 ? "asfloat(0x7F800000u)" : "asfloat(0xFF800000u)";
      }
      return fmt::format("asfloat(0x{:08X}u)", *reinterpret_cast<const uint32_t *>(&v));
    }

    // Common declarations of every translated shader.
    const char kHeader[] = R"(// Generated by the AO2 native renderer (Xenos -> HLSL).
cbuffer xe_float_constants : register(b0) { float4 xe_c[256]; };
cbuffer xe_system : register(b1) {
  uint xe_flags;
  uint xe_vertex_index_offset;
  uint xe_alpha_func;
  float xe_alpha_ref;
  float4 xe_ndc_scale;
  float4 xe_ndc_offset;
  float4 xe_color_exp_bias;
  uint4 xe_vertex_index_range;
  float4 xe_resolution_scale;
  uint4 xe_bool_loop[10];
  uint4 xe_tex_info[16];
  uint4 xe_vfetch[48];
  float4 xe_tex_size[16];
  float4 xe_tex_rcp[16];
};
ByteAddressBuffer xe_shared_memory : register(t0, space1);

struct XeVertexOut {
  float4 o[16] : TEXCOORD0;
  float4 misc : TEXCOORD16;
  float4 position : SV_Position;
};

float4 xe_mul(float4 a, float4 b) {
  return (min(abs(a), abs(b)) == 0.0) ? 0.0 : a * b;
}
float xe_mul1(float a, float b) {
  return (min(abs(a), abs(b)) == 0.0) ? 0.0 : a * b;
}
float4 xe_max(float4 a, float4 b) { return (a >= b) ? a : b; }
float4 xe_min(float4 a, float4 b) { return (a < b) ? a : b; }
float xe_max1(float a, float b) { return (a >= b) ? a : b; }
float xe_min1(float a, float b) { return (a < b) ? a : b; }
uint4 xe_swap(uint4 v, uint endian) {
  if (endian == 1u || endian == 2u) {
    v = ((v & 0x00FF00FFu) << 8) | ((v >> 8) & 0x00FF00FFu);
  }
  if (endian == 2u || endian == 3u) {
    v = (v << 16) | (v >> 16);
  }
  return v;
}
uint2 xe_vfetch_constant(uint index) {
  uint4 v = xe_vfetch[index >> 1];
  return (index & 1u) ? v.zw : v.xy;
}
// Per-component texture post-processing: 2 = biased (x * 2 - 1), 3 = gamma.
float4 xe_tex_post(float4 v, uint4 info) {
  // Most fetches have neither (the same for every pixel of a draw): one
  // test instead of two per component.
  [branch] if ((info.x & 0xFFu) != 0u)
  [unroll] for (uint i = 0; i < 4; ++i) {
    uint mode = (info.x >> (i * 2u)) & 3u;
    if (mode == 2u) {
      v[i] = v[i] * 2.0 - 1.0;
    } else if (mode == 3u) {
      // Xenos piecewise-linear gamma to linear (xenos::PWLGammaToLinear).
      float g = saturate(v[i]);
      float scale = g >= 192.0 / 255.0 ? 8.0 / 1024.0 : (g >= 96.0 / 255.0 ? 4.0 / 1024.0 : (g >= 64.0 / 255.0 ? 2.0 / 1024.0 : 1.0 / 1024.0));
      float offset = g >= 192.0 / 255.0 ? -1024.0 : (g >= 96.0 / 255.0 ? -256.0 : (g >= 64.0 / 255.0 ? -64.0 : 0.0));
      float l = g * (255.0 * 1024.0 * scale) + offset;
      v[i] = (l + trunc(l * scale)) * (1.0 / 1023.0);
    }
  }
  return v * asfloat(info.y);
}
)";
