  std::vector<uint8_t> HlslShaderTranslator::CompleteTranslation()
  {
    CloseExecConditional();
    Close(); // last label block
    if (use_loop_)
    {
      Line("break;");
      Close(); // main loop
    }

    const Shader &shader = current_shader();
    HlslModification mod = modification();
    uint32_t regs = std::max(register_count(), 1u);
    std::string s = kHeader;

    // Texture/sampler declarations (one entry per tfetch, bindings shared).
    uint32_t declared = 0;
    for (const auto &b : shader.texture_bindings())
    {
      if (b.binding_index >= 16 || (declared & (1u << b.binding_index)))
      {
        continue;
      }
      declared |= 1u << b.binding_index;
      const char *type = "Texture2D";
      switch (b.fetch_instr.dimension)
      {
      case xenos::FetchOpDimension::k3DOrStacked:
        type = "Texture3D";
        break;
      case xenos::FetchOpDimension::kCube:
        type = "TextureCube";
        break;
      default:
        break;
      }
      s += fmt::format("{} xe_tex{} : register(t{});\n", type, b.binding_index, b.binding_index);
      s += fmt::format("SamplerState xe_smp{} : register(s{});\n", b.binding_index, b.binding_index);
    }

    if (is_vertex_shader())
    {
      s += "XeVertexOut main(uint xe_vertex_id : SV_VertexID) {\n";
      s += "  XeVertexOut xe_out = (XeVertexOut)0;\n";
      s += "  float4 xe_position = float4(0.0, 0.0, 0.0, 1.0);\n";
      s += fmt::format("  float4 xe_r[{}];\n", regs);
      s += fmt::format("  [unroll] for (uint xe_i = 0u; xe_i < {}u; ++xe_i) {{ xe_r[xe_i] = 0.0; }}\n",
                       regs);
      // Indexed draws can fetch the guest index buffer here (z = address,
      // w = enable | 32-bit << 1 | endian << 2) instead of a host index buffer.
      s += R"(  uint xe_vid = xe_vertex_id;
  if ((xe_vertex_index_range.w & 1u) != 0u) {
    bool xe_i32 = (xe_vertex_index_range.w & 2u) != 0u;
    uint xe_ia = xe_vertex_index_range.z + xe_vertex_id * (xe_i32 ? 4u : 2u);
    uint xe_iw = xe_shared_memory.Load(xe_ia & ~3u);
    uint xe_ie = (xe_vertex_index_range.w >> 2) & 3u;
    if (xe_i32) {
      xe_vid = xe_swap(uint4(xe_iw, 0u, 0u, 0u), xe_ie).x;
    } else {
      xe_vid = (xe_ia & 2u) != 0u ? (xe_iw >> 16) : (xe_iw & 0xFFFFu);
      if (xe_ie == 1u || xe_ie == 2u) { xe_vid = ((xe_vid & 0xFFu) << 8) | (xe_vid >> 8); }
    }
  }
)";
      s += "  int xe_index = int(xe_vid) + int(xe_vertex_index_offset);\n";
      s += "  xe_index = clamp(xe_index, int(xe_vertex_index_range.x), int(xe_vertex_index_range.y));\n";
      s += "  xe_r[0].x = float(xe_index);\n";
      s += body_;
      s += R"(  if ((xe_flags & 1u) == 0u) { xe_position.w = 1.0 / xe_position.w; }
  if ((xe_flags & 2u) != 0u) { xe_position.xy *= xe_position.w; }
  if ((xe_flags & 4u) != 0u) { xe_position.z *= xe_position.w; }
  xe_position.xyz = xe_position.xyz * xe_ndc_scale.xyz + xe_ndc_offset.xyz * xe_position.w;
  if ((asuint(xe_out.misc.z) & 0x7FFFFFFFu) != 0u) { xe_position.w = asfloat(0x7FC00000u); }
  xe_out.position = xe_position;
  return xe_out;
}
)";
    }
    else
    {
      // The menu probe: only color 0, the probed coordinates.
      bool probe = mod.probe_binding != 0;
      uint32_t color_targets = probe ? 1u : shader.writes_color_targets();
      s += "struct XePixelOut {\n";
      for (uint32_t i = 0; i < 4; ++i)
      {
        if (color_targets & (1u << i))
        {
          s += fmt::format("  float4 c{} : SV_Target{};\n", i, i);
        }
      }
      if (shader.writes_depth())
      {
        s += "  float depth : SV_Depth;\n";
      }
      if (!color_targets && !shader.writes_depth())
      {
        s += "  float4 c0 : SV_Target0;\n";
      }
      s += "};\n";
      s += "XePixelOut main(XeVertexOut xe_in, bool xe_front_face : SV_IsFrontFace) {\n";
      s += "  XePixelOut xe_result = (XePixelOut)0;\n";
      s += "  float4 xe_color[4] = { 0.0.xxxx, 0.0.xxxx, 0.0.xxxx, 0.0.xxxx };\n";
      s += "  float xe_depth = xe_in.position.z;\n";
      if (probe)
      {
        // Only here: the other shaders' text (and their cached DXBC) stays as it was.
        s += "  float4 xe_probe = 0.0.xxxx;\n";
      }
      s += fmt::format("  float4 xe_r[{}];\n", regs);
      s += fmt::format("  [unroll] for (uint xe_i = 0u; xe_i < {}u; ++xe_i) {{ xe_r[xe_i] = "
                       "xe_i < 16u ? xe_in.o[min(xe_i, 15u)] : 0.0; }}\n",
                       regs);
      if (mod.param_gen_register != 31 && mod.param_gen_register < regs)
      {
        // ps_param_gen: XY = pixel position without the 0.5 center offset,
        // sign of X = back face.
        // Render targets may be scaled: positions are in guest pixels (the
        // one the host pixel's centre is in; .z = the scale in quarters, in
        // whole numbers so that centres on a guest pixel edge do not round).
        s += "  float2 xe_pixel = floor((floor(xe_in.position.xy) * 4.0 + 2.0) / xe_resolution_scale.z);\n";
        s += fmt::format("  xe_r[{}] = float4(xe_front_face ? xe_pixel.x : -xe_pixel.x, xe_pixel.y, 0.0, 0.0);\n",
                         uint32_t(mod.param_gen_register));
      }
      s += body_;
      if (mod.alpha_test)
      {
        s += R"(  if ((xe_flags & 8u) != 0u) {
    float a = xe_color[0].a;
    bool xe_pass = true;
    switch (xe_alpha_func) {
      case 0u: xe_pass = false; break;
      case 1u: xe_pass = a < xe_alpha_ref; break;
      case 2u: xe_pass = a == xe_alpha_ref; break;
      case 3u: xe_pass = a <= xe_alpha_ref; break;
      case 4u: xe_pass = a > xe_alpha_ref; break;
      case 5u: xe_pass = a != xe_alpha_ref; break;
      case 6u: xe_pass = a >= xe_alpha_ref; break;
      default: break;
    }
    if (!xe_pass) { discard; }
  }
)";
      }
      if (probe)
      {
        s += "  if (xe_probe.w == 0.0) { discard; }\n  xe_result.c0 = xe_probe;\n";
      }
      else
      {
        for (uint32_t i = 0; i < 4; ++i)
        {
          if (color_targets & (1u << i))
          {
            s += fmt::format("  xe_result.c{0} = xe_color[{0}] * xe_color_exp_bias[{0}];\n", i);
          }
        }
      }
      if (shader.writes_depth())
      {
        s += "  xe_result.depth = xe_depth;\n";
      }
      s += "  return xe_result;\n}\n";
    }
    return std::vector<uint8_t>(s.begin(), s.end());
  }
