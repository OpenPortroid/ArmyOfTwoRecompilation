  void HlslShaderTranslator::ProcessVertexFetchInstruction(const ParsedVertexFetchInstruction &instr)
  {
    if (!instr.is_mini_fetch && position_register_ == -1)
    {
      // First full fetch: candidate for the pass-through position.
      const auto &at = instr.attributes;
      const InstructionResult &res = instr.result;
      bool usable = !instr.is_predicated && !conditional_exec_ &&
                    res.storage_target == InstructionStorageTarget::kRegister &&
                    res.storage_addressing_mode == InstructionStorageAddressingMode::kAbsolute &&
                    (res.GetUsedWriteMask() & 0b11) == 0b11 && res.components[0] == SwizzleSource::kX &&
                    res.components[1] == SwizzleSource::kY && !at.exp_adjust &&
                    (at.data_format == xenos::VertexFormat::k_32_32_FLOAT ||
                     at.data_format == xenos::VertexFormat::k_32_32_32_FLOAT ||
                     at.data_format == xenos::VertexFormat::k_32_32_32_32_FLOAT);
      position_register_ = usable ? int32_t(res.storage_index) : -2;
      if (usable)
      {
        position_fetch_.valid = true;
        position_fetch_.fetch_constant = instr.operands[1].storage_index;
        position_fetch_.offset = at.offset;
        position_fetch_.stride = at.stride;
        position_fetch_.format = at.data_format;
      }
    }
    else
    {
      TrackRegisterWrite(instr.result);
    }
    SetInstructionPredication(instr.is_predicated, instr.predicate_condition);
    const auto &at = instr.attributes;
    uint32_t used = instr.result.GetUsedResultComponents();
    uint32_t needed_words = xenos::GetVertexFormatNeededWords(at.data_format, used);
    uint32_t fetch_constant = instr.operands[1].storage_index;
    Open("");
    if (!instr.is_mini_fetch)
    {
      Line(fmt::format("uint2 xe_vf = xe_vfetch_constant({}u);", fetch_constant));
      if (at.stride)
      {
        std::string index = OperandComponent(instr.operands[0], 0);
        if (at.is_index_rounded)
        {
          index = "(" + index + " + 0.5)";
        }
        Line(fmt::format("xe_vfetch_address = (xe_vf.x & 0x1FFFFFFCu) + uint(int(floor({}))) * {}u;",
                         index, at.stride * 4));
      }
      else
      {
        Line("xe_vfetch_address = xe_vf.x & 0x1FFFFFFCu;");
      }
    }
    else
    {
      Line(fmt::format("uint2 xe_vf = xe_vfetch_constant({}u);", fetch_constant));
    }
    if (!needed_words)
    {
      StoreResult(instr.result, "float4(0.0, 0.0, 0.0, 0.0)");
      Close();
      return;
    }
    Line("uint4 xe_w = 0u;");
    for (uint32_t i = 0; i < 4; ++i)
    {
      if (needed_words & (1u << i))
      {
        Line(fmt::format("xe_w.{} = xe_shared_memory.Load(xe_vfetch_address + {}u);", kComp[i],
                         uint32_t(int32_t((at.offset + int32_t(i)) * 4))));
      }
    }
    Line("xe_w = xe_swap(xe_w, xe_vf.y & 3u);");
    Line("float4 xe_v = 0.0;");

    uint32_t widths[4] = {}, offsets[4] = {};
    bool second_word_zw = false;
    switch (at.data_format)
    {
    case xenos::VertexFormat::k_8_8_8_8:
      widths[0] = widths[1] = widths[2] = widths[3] = 8;
      offsets[1] = 8;
      offsets[2] = 16;
      offsets[3] = 24;
      break;
    case xenos::VertexFormat::k_2_10_10_10:
      widths[0] = widths[1] = widths[2] = 10;
      widths[3] = 2;
      offsets[1] = 10;
      offsets[2] = 20;
      offsets[3] = 30;
      break;
    case xenos::VertexFormat::k_10_11_11:
      widths[0] = widths[1] = 11;
      widths[2] = 10;
      offsets[1] = 11;
      offsets[2] = 22;
      break;
    case xenos::VertexFormat::k_11_11_10:
      widths[0] = 10;
      widths[1] = widths[2] = 11;
      offsets[1] = 10;
      offsets[2] = 21;
      break;
    case xenos::VertexFormat::k_16_16:
      widths[0] = widths[1] = 16;
      offsets[1] = 16;
      break;
    case xenos::VertexFormat::k_16_16_16_16:
      widths[0] = widths[1] = widths[2] = widths[3] = 16;
      offsets[1] = offsets[3] = 16;
      second_word_zw = true;
      break;
    default:
      break;
    }
    if (widths[0])
    {
      Line(second_word_zw ? "uint4 xe_bits = xe_w.xxyy;" : "uint4 xe_bits = xe_w.xxxx;");
      for (uint32_t i = 0; i < 4; ++i)
      {
        if (!widths[i])
        {
          continue;
        }
        if (at.is_signed)
        {
          Line(fmt::format("xe_v.{} = float(int(xe_bits.{} << {}u) >> {});", kComp[i], kComp[i],
                           32 - widths[i] - offsets[i], 32 - widths[i]));
          if (!at.is_integer)
          {
            if (at.signed_rf_mode == xenos::SignedRepeatingFractionMode::kNoZero)
            {
              float zero = 1.0f / float((1u << widths[i]) - 1);
              Line(fmt::format("xe_v.{0} = xe_v.{0} * {1} + {2};", kComp[i], F(2.0f * zero), F(zero)));
            }
            else if (widths[i] > 2)
            {
              Line(fmt::format("xe_v.{0} = max(xe_v.{0} * {1}, -1.0);", kComp[i],
                               F(1.0f / float((1u << (widths[i] - 1)) - 1))));
            }
            else
            {
              Line(fmt::format("xe_v.{0} = max(xe_v.{0}, -1.0);", kComp[i]));
            }
          }
        }
        else
        {
          Line(fmt::format("xe_v.{} = float((xe_bits.{} >> {}u) & {}u);", kComp[i], kComp[i],
                           offsets[i], (1u << widths[i]) - 1));
          if (!at.is_integer)
          {
            Line(fmt::format("xe_v.{0} *= {1};", kComp[i], F(1.0f / float((1u << widths[i]) - 1))));
          }
        }
      }
    }
    else
    {
      switch (at.data_format)
      {
      case xenos::VertexFormat::k_16_16_FLOAT:
      case xenos::VertexFormat::k_16_16_16_16_FLOAT:
        Line("xe_v = f16tof32(uint4(xe_w.x, xe_w.x >> 16, xe_w.y, xe_w.y >> 16));");
        break;
      case xenos::VertexFormat::k_32:
      case xenos::VertexFormat::k_32_32:
      case xenos::VertexFormat::k_32_32_32_32:
        if (at.is_signed)
        {
          Line("xe_v = float4(int4(xe_w));");
          if (!at.is_integer)
          {
            Line(at.signed_rf_mode == xenos::SignedRepeatingFractionMode::kNoZero
                     ? "xe_v = xe_v * (1.0 / 2147483647.5) + (0.5 / 2147483647.5);"
                     : "xe_v *= 1.0 / 2147483647.0;");
          }
        }
        else
        {
          Line("xe_v = float4(xe_w);");
          if (!at.is_integer)
          {
            Line("xe_v *= 1.0 / 4294967295.0;");
          }
        }
        break;
      case xenos::VertexFormat::k_32_FLOAT:
      case xenos::VertexFormat::k_32_32_FLOAT:
      case xenos::VertexFormat::k_32_32_32_FLOAT:
      case xenos::VertexFormat::k_32_32_32_32_FLOAT:
        Line("xe_v = asfloat(xe_w);");
        break;
      default:
        EmitTranslationError("unsupported vertex format", false);
        break;
      }
    }
    if (at.exp_adjust)
    {
      Line(fmt::format("xe_v *= {};", F(std::ldexp(1.0f, at.exp_adjust))));
    }
    uint32_t format_components =
        (1u << xenos::GetVertexFormatComponentCount(at.data_format)) - 1;
    for (uint32_t i = 0; i < 4; ++i)
    {
      if ((used & (1u << i)) && !(format_components & (1u << i)))
      {
        Line(fmt::format("xe_v.{} = 0.0;", kComp[i]));
      }
    }
    // Normalized and integer formats can't hold infinity or NaN: only the
    // 16- and 32-bit float ones make the multiplications after them xe_mul.
    bool float_format = at.data_format == xenos::VertexFormat::k_16_16_FLOAT ||
                        at.data_format == xenos::VertexFormat::k_16_16_16_16_FLOAT ||
                        at.data_format == xenos::VertexFormat::k_32_FLOAT ||
                        at.data_format == xenos::VertexFormat::k_32_32_FLOAT ||
                        at.data_format == xenos::VertexFormat::k_32_32_32_FLOAT ||
                        at.data_format == xenos::VertexFormat::k_32_32_32_32_FLOAT;
    StoreResult(instr.result, "xe_v", float_format || !track_finite_ ? 0xF : 0);
    Close();
  }

  void HlslShaderTranslator::ProcessTextureFetchInstruction(const ParsedTextureFetchInstruction &instr)
  {
    TrackRegisterWrite(instr.result);
    SetInstructionPredication(instr.is_predicated, instr.predicate_condition);
    switch (instr.opcode)
    {
    case FetchOpcode::kSetTextureLod:
      Line("xe_lod = " + OperandComponent(instr.operands[0], 0) + ";");
      return;
    case FetchOpcode::kSetTextureGradientsHorz:
      Line("xe_grad_h = " + Operand(instr.operands[0]) + ";");
      return;
    case FetchOpcode::kSetTextureGradientsVert:
      Line("xe_grad_v = " + Operand(instr.operands[0]) + ";");
      return;
    default:
      break;
    }
    if (!instr.has_result())
    {
      return;
    }
    if (instr.opcode == FetchOpcode::kGetTextureGradients)
    {
      std::string c = Operand(instr.operands[0]);
      if (is_pixel_shader())
      {
        StoreResult(instr.result, fmt::format("float4(ddx_coarse({0}.x), ddy_coarse({0}.x), "
                                              "ddx_coarse({0}.y), ddy_coarse({0}.y))",
                                              c));
      }
      else
      {
        StoreResult(instr.result, "float4(0.0, 0.0, 0.0, 0.0)");
      }
      return;
    }
    if (instr.opcode == FetchOpcode::kGetTextureBorderColorFrac)
    {
      StoreResult(instr.result, "float4(0.0, 0.0, 0.0, 0.0)");
      return;
    }

    // Find the binding of this fetch constant.
    uint32_t fetch_constant = instr.operands[1].storage_index;
    uint32_t binding = UINT32_MAX;
    for (const auto &b : current_shader().texture_bindings())
    {
      if (b.fetch_constant == fetch_constant)
      {
        binding = uint32_t(b.binding_index);
        break;
      }
    }
    if (binding == UINT32_MAX || binding >= 16)
    {
      EmitTranslationError("texture binding not found", false);
      StoreResult(instr.result, "float4(0.0, 0.0, 0.0, 0.0)");
      return;
    }
    std::string tex = fmt::format("xe_tex{}", binding);
    std::string smp = fmt::format("xe_smp{}", binding);
    std::string c = Operand(instr.operands[0]);
    const auto &at = instr.attributes;
    const float eps = 1.5f / 1024.0f;
    bool computed_lod = at.use_computed_lod && (is_pixel_shader() || at.use_register_gradients);

    Open("");
    Line(fmt::format("float4 xe_tc = {};", c));
    std::string coord;
    switch (instr.dimension)
    {
    case xenos::FetchOpDimension::k1D:
    case xenos::FetchOpDimension::k2D:
    {
      // Coordinates are relative to the guest texture; resolved textures
      // live in larger host resources (pitch x height), xe_tex_info.zw =
      // guest size / host size.
      bool is_1d = instr.dimension == xenos::FetchOpDimension::k1D;
      // The host size comes from the constants: GetDimensions is a texture
      // instruction of its own (TXQ), as costly as the fetch on some GPUs.
      Line(fmt::format("float2 xe_ts = asfloat(xe_tex_info[{}].zw);", binding));
      Line(fmt::format("float2 xe_host_size = xe_tex_size[{}].xy;", binding));
      // The guest size: what unnormalized coordinates and weights need; the
      // offset of a normalized fetch takes its reciprocal from the constants
      // (no per-pixel divisions).
      bool guest_size = at.unnormalized_coordinates || instr.opcode == FetchOpcode::kGetTextureWeights;
      if (guest_size)
      {
        Line(fmt::format("float xe_tw = xe_tex_size[{0}].x, xe_th = xe_tex_size[{0}].y;", binding));
        // Host texels per guest texel of a resolved texture, in quarters (0: not resolved).
        Line(fmt::format("float xe_tscale = max(float((xe_tex_info[{}].x >> 16) & 0xFFu) * 0.25, 1.0);", binding));
        Line("xe_tw *= xe_ts.x / xe_tscale; xe_th *= xe_ts.y / xe_tscale;");
      }
      Line(is_1d ? "float2 xe_uv = float2(xe_tc.x, 0.5);" : "float2 xe_uv = xe_tc.xy;");
      if (at.unnormalized_coordinates)
      {
        Line(is_1d ? "xe_uv.x /= xe_tw;" : "xe_uv /= float2(xe_tw, xe_th);");
      }
      if (instr.opcode != FetchOpcode::kGetTextureComputedLod)
      {
        if (guest_size)
        {
          Line(fmt::format("xe_uv += float2({}, {}) / float2(xe_tw, xe_th);", F(at.offset_x + eps),
                           F(is_1d ? 0.0f : at.offset_y + eps)));
        }
        else
        {
          Line(fmt::format("xe_uv += float2({}, {}) * xe_tex_rcp[{}].xy;", F(at.offset_x + eps),
                           F(is_1d ? 0.0f : at.offset_y + eps), binding));
        }
      }
      if (is_pixel_shader() && !is_1d && instr.opcode == FetchOpcode::kTextureFetch &&
          modification().probe_binding == binding + 1)
      {
        Line("xe_probe = float4(xe_uv, 0.0, 1.0);");
      }
      if (instr.opcode == FetchOpcode::kGetTextureWeights)
      {
        StoreResult(instr.result, "float4(frac(xe_uv * float2(xe_tw, xe_th) - 0.5), 0.0, 0.0)");
        Close();
        return;
      }
      Open("if (any(xe_ts != 1.0))");
      // Stay inside the guest part of the host resource (edge clamp): up to
      // the centre of its last host texel (at a fractional scale the part
      // may end inside a texel, which then is the next guest texel's).
      Line("xe_uv = clamp(xe_uv * xe_ts, 0.5 / xe_host_size, (ceil(xe_ts * xe_host_size - 0.502) - 0.5) / xe_host_size);");
      Close();
      if (at.use_register_gradients)
      {
        Line("float2 xe_gh = xe_grad_h.xy * xe_ts, xe_gv = xe_grad_v.xy * xe_ts;");
      }
      coord = "xe_uv";
      break;
    }
    case xenos::FetchOpDimension::k3DOrStacked:
    {
      Line(fmt::format("float xe_tw = xe_tex_size[{0}].x, xe_th = xe_tex_size[{0}].y, xe_td = xe_tex_size[{0}].z;",
                       binding));
      Line("float3 xe_uvw = xe_tc.xyz;");
      if (at.unnormalized_coordinates)
      {
        Line("xe_uvw /= float3(xe_tw, xe_th, xe_td);");
      }
      Line(fmt::format("xe_uvw += float3({}, {}, {}) / float3(xe_tw, xe_th, xe_td);",
                       F(at.offset_x + eps), F(at.offset_y + eps), F(at.offset_z + eps)));
      coord = "xe_uvw";
      if (instr.opcode == FetchOpcode::kGetTextureWeights)
      {
        StoreResult(instr.result,
                    "float4(frac(xe_uvw * float3(xe_tw, xe_th, xe_td) - 0.5), 0.0)");
        Close();
        return;
      }
      break;
    }
    case xenos::FetchOpDimension::kCube:
    {
      // (SC + 1, TC + 1, face) back to a direction.
      Line("float2 xe_st = xe_tc.xy * 2.0 - 3.0;");
      Line("uint xe_face = min(uint(max(xe_tc.z, 0.0)), 5u);");
      Line("bool xe_neg = (xe_face & 1u) != 0u;");
      Line("float3 xe_dir;");
      Open("if ((xe_face >> 1) == 0u)");
      Line("xe_dir = float3(xe_neg ? -1.0 : 1.0, -xe_st.y, xe_neg ? xe_st.x : -xe_st.x);");
      Close();
      Open("else if ((xe_face >> 1) == 1u)");
      Line("xe_dir = float3(xe_st.x, xe_neg ? -1.0 : 1.0, xe_neg ? -xe_st.y : xe_st.y);");
      Close();
      Open("else");
      Line("xe_dir = float3(xe_neg ? -xe_st.x : xe_st.x, -xe_st.y, xe_neg ? -1.0 : 1.0);");
      Close();
      coord = "xe_dir";
      if (instr.opcode == FetchOpcode::kGetTextureWeights)
      {
        StoreResult(instr.result, "float4(0.0, 0.0, 0.0, 0.0)");
        Close();
        return;
      }
      break;
    }
    }

    if (instr.opcode == FetchOpcode::kGetTextureComputedLod)
    {
      if (is_pixel_shader())
      {
        StoreResult(instr.result,
                    fmt::format("{}.CalculateLevelOfDetailUnclamped({}, {}).xxxx", tex, smp, coord));
      }
      else
      {
        StoreResult(instr.result, "float4(0.0, 0.0, 0.0, 0.0)");
      }
      Close();
      return;
    }

    std::string sample;
    std::string bias = at.lod_bias != 0.0f ? F(at.lod_bias) : "";
    if (at.use_register_gradients)
    {
      bool planar = instr.dimension == xenos::FetchOpDimension::k2D || instr.dimension == xenos::FetchOpDimension::k1D;
      sample = planar ? fmt::format("{}.SampleGrad({}, {}, xe_gh, xe_gv)", tex, smp, coord)
                      : fmt::format("{}.SampleGrad({}, {}, xe_grad_h.xyz, xe_grad_v.xyz)", tex, smp, coord);
    }
    else if (computed_lod && !at.use_register_lod)
    {
      sample = bias.empty() ? fmt::format("{}.Sample({}, {})", tex, smp, coord)
                            : fmt::format("{}.SampleBias({}, {}, {})", tex, smp, coord, bias);
    }
    else
    {
      std::string lod = at.use_register_lod ? "xe_lod" : "0.0";
      if (!bias.empty())
      {
        lod += " + " + bias;
      }
      sample = fmt::format("{}.SampleLevel({}, {}, {})", tex, smp, coord, lod);
    }
    StoreResult(instr.result, fmt::format("xe_tex_post({}, xe_tex_info[{}])", sample, binding), 0);
    Close();
  }

